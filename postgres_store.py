"""Postgres connection adapter for the existing event service.

Local runs continue to use SQLite. Cloud runs use DATABASE_URL and row locks.
"""
from __future__ import annotations
import re
from urllib.parse import urlsplit,urlunsplit
import psycopg
from psycopg import sql
from psycopg.rows import dict_row


def schema_name(value):
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,62}',value):
        raise ValueError('Invalid database schema')
    return value


class PostgresConnection:
    def __init__(self,url,schema='inguin_event'):
        self.schema=schema_name(schema)
        self.raw=psycopg.connect(url,autocommit=True,row_factory=dict_row,
                                 connect_timeout=15,prepare_threshold=None)

    def __enter__(self):return self
    def __exit__(self,kind,value,tb):
        try:
            if kind:self.raw.rollback()
            else:self.raw.commit()
        finally:self.raw.close()

    def execute(self,statement,params=()):
        text=statement.strip()
        if text.upper()=='BEGIN IMMEDIATE':text='BEGIN'
        # Serialize modifications of an existing participant without serializing
        # participants who are issuing different invitations.
        if re.match(r'SELECT (?:\*|checked_at) FROM participants WHERE',text,re.I):
            text+=' FOR UPDATE'
        if text.upper().startswith('INSERT INTO PARTICIPANTS('):
            text+=' ON CONFLICT(normalized_name,last2) DO NOTHING'
        if text.upper()=='DELETE FROM QUESTIONS':
            self.raw.execute(sql.SQL('SELECT id FROM {}.config WHERE id=1 FOR UPDATE').format(sql.Identifier(self.schema)))
        text=text.replace('instr(normalized_name,?)','strpos(normalized_name,?)')
        # PgBouncer transaction pooling does not preserve SET search_path.
        # Qualify every table instead of relying on session state.
        text=re.sub(r'\b(FROM|INTO|UPDATE|JOIN)\s+(config|questions|participants|admin_sessions|login_failures)\b',
                    lambda m:m.group(1)+' "'+self.schema+'".'+m.group(2),text,flags=re.I)
        return self.raw.execute(text.replace('?','%s'),params)

    def executemany(self,statement,values):
        statement=re.sub(r'\b(FROM|INTO|UPDATE|JOIN)\s+(config|questions|participants|admin_sessions|login_failures)\b',
                         lambda m:m.group(1)+' "'+self.schema+'".'+m.group(2),statement,flags=re.I)
        cursor=self.raw.cursor();cursor.executemany(statement.replace('?','%s'),values);return cursor
    def commit(self):self.raw.commit()
    def rollback(self):self.raw.rollback()


def initialize(url,schema,seed):
    schema=schema_name(schema)
    parts=urlsplit(url)
    credentials,at,host=parts.netloc.rpartition('@')
    if at:
        url=urlunsplit(parts._replace(netloc=credentials+'@'+host.replace('-pooler.','.',1)))
    with psycopg.connect(url,autocommit=True,row_factory=dict_row,connect_timeout=15,prepare_threshold=None) as raw:
        with raw.transaction():
            raw.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s,0))',('inguin-schema:'+schema,))
            raw.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
            raw.execute(sql.SQL('SET LOCAL search_path TO {}, public').format(sql.Identifier(schema)))
            raw.execute('''CREATE TABLE IF NOT EXISTS config (
              id INTEGER PRIMARY KEY CHECK(id=1),revision INTEGER NOT NULL DEFAULT 1,
              bank_version INTEGER NOT NULL DEFAULT 6)''')
            raw.execute('''CREATE TABLE IF NOT EXISTS questions (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              group_key TEXT NOT NULL,prompt TEXT NOT NULL,options TEXT NOT NULL,
              answer INTEGER NOT NULL,image TEXT NOT NULL DEFAULT '',
              option_images TEXT NOT NULL DEFAULT '[]',position INTEGER NOT NULL,
              accepted_answers TEXT NOT NULL DEFAULT '[]')''')
            raw.execute('''CREATE TABLE IF NOT EXISTS participants (
              participant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              name TEXT NOT NULL,normalized_name TEXT NOT NULL,last2 TEXT NOT NULL,
              joined_at TEXT NOT NULL,question_ids TEXT NOT NULL,revision INTEGER NOT NULL,
              completed_at TEXT,invite_code TEXT UNIQUE,checked_at TEXT,
              UNIQUE(normalized_name,last2))''')
            raw.execute('CREATE INDEX IF NOT EXISTS participants_completed ON participants(completed_at)')
            raw.execute('''CREATE TABLE IF NOT EXISTS admin_sessions (
              token_hash TEXT PRIMARY KEY,csrf TEXT NOT NULL,expires BIGINT NOT NULL)''')
            raw.execute('''CREATE TABLE IF NOT EXISTS login_failures (
              ip TEXT NOT NULL,failed_at BIGINT NOT NULL)''')
            raw.execute('CREATE INDEX IF NOT EXISTS login_failure_lookup ON login_failures(ip,failed_at)')
            raw.execute('INSERT INTO config(id,revision,bank_version) VALUES(1,1,6) ON CONFLICT(id) DO NOTHING')
            if not raw.execute('SELECT 1 FROM questions LIMIT 1').fetchone():
                # Reuse the exact question bank; no cloud-only answers or copies.
                class SeedConnection:
                    def execute(self,query,params=()):return raw.execute(query.replace('?','%s'),params)
                seed(SeedConnection())
